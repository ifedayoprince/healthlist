import { sql } from "drizzle-orm";
import { relations } from "drizzle-orm/_relations";
import { boolean, integer, jsonb, pgEnum, pgTable, text, timestamp, unique, uniqueIndex, uuid, varchar } from "drizzle-orm/pg-core";

export const users = pgTable("users", {
    id: uuid('id').defaultRandom().primaryKey(),
    name: varchar('name', { length: 255 }).notNull(),
    email: varchar('email', { length: 255 }).notNull().unique(),
    password: text('password').notNull(),
    joinedAt: timestamp("joined_at", { withTimezone: true }).defaultNow()
});

export const authSessions = pgTable("auth_sessions", {
    id: uuid('id').defaultRandom().primaryKey(),
    token: varchar('token', { length: 50 }).notNull(),
    userId: uuid('user_id')
        .notNull()
        .unique()
        .references(() => users.id),
    issuedAt: timestamp('issued_at', { withTimezone: true }).defaultNow().notNull(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    maxLifespan: timestamp('max_lifespan', { withTimezone: true }).notNull(),
})

export const assessments = pgTable("assessments", {
    id: uuid('id').defaultRandom().primaryKey(),
    userId: uuid('user_id')
        .notNull()
        .unique()
        .references(() => users.id)
});

export const questionTypesEnum = pgEnum('question_types', [
    "MULTI_SELECT",
    "YES_NO",
    "YES_NO_TEXT",
    "TEXT_LIST"
]);
export const assessmentQuestions = pgTable("assessment_questions", {
    id: uuid('id').defaultRandom().primaryKey(),
    key: varchar('key', { length: 50 }).notNull().unique(),
    question: text('question').notNull(),
    isRequired: boolean('is_required').default(false).notNull(),
    type: questionTypesEnum('type').notNull(),
    options: jsonb('options').$type<{
        key: string;
        value: string;
    }[]>()
});

export const assessmentAnswers = pgTable("assessment_answers", {
    id: uuid('id').defaultRandom().primaryKey(),
    assessmentId: uuid('assessment_id')
        .notNull()
        .references(() => assessments.id),
    assessmentQuestionId: uuid('assessment_question_id')
        .notNull()
        .references(() => assessmentQuestions.id),
    answer: jsonb('answer')
        .$type<string | string[] | boolean>(),
    answeredAt: timestamp('answered_at', { withTimezone: true }).defaultNow()
}, (table) => [
    unique().on(table.assessmentId, table.assessmentQuestionId)
]);


export const listings = pgTable("listings", {
    id: uuid('id').defaultRandom().primaryKey(),
    slug: varchar('slug', { length: 50 }).notNull(),
    // Using only brand name for now rather than setting up robust roles
    brand: varchar('brand', { length: 20 }).notNull(),
    reviews: integer('reviews').default(0).notNull(),
    productImage: varchar('product_image', { length: 255 }),
    requiredInfo: varchar("required_info")
        .array()
        .default([])
        .notNull(),
    createdAt: timestamp('created_at', {withTimezone: true}).defaultNow().notNull()
});
export type Listing = typeof listings.$inferSelect;

export const listingDocuments = pgTable("listing_documents", {
    id: uuid('id').defaultRandom().primaryKey(),
    listingId: uuid('listing_id')
        .notNull()
        .references(() => listings.id),
    version: integer('version').default(0).notNull(),
    isActive: boolean('is_active').default(false).notNull(),
    name: varchar('name', { length: 50 }).notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),

    excerpt: varchar('excerpt', {length: 255}).default(""),
    metadata: jsonb('metadata').$type<{
        price: number;
        category: string[];
    }>(),

    /** On listing submission or document update, a SOTA model will conduct deep-research to verify the claims and statements in the `body` against known information about the composition of the drug/product. */
    body: text('body').default(""),

    /** Tags to help with retrieval. Ideally could contain:
     * - Common patient-friendly terms
     * - Symptoms
     * - Synonmys
     * 
     * Could be auto-generated by a SOTA model after it does deep-research to validate the claims of the product and it's composition (e.g. compounds used in manufacture).
     */
    search_tags: text('search_tags')
        .array()
        .default([])
        .notNull(),
}, (table) => [
    unique().on(table.listingId, table.version),
    uniqueIndex('listing_doc_one_active_idx')
        .on(table.listingId)
        .where(sql`${table.isActive} = true`)
]);
export type ListingDocument = typeof listingDocuments.$inferSelect;

export const intakeStatusEnum = pgEnum("intake_status", [
    "PENDING",
    "IN_REVIEW",
    "REJECTED",
    "APPROVED"
]);
export const intakes = pgTable("intakes", {
    id: uuid('id').defaultRandom().primaryKey(),
    key: varchar('key', { length: 50 }).notNull().unique(),
    userId: uuid('user_id').notNull().references(() => users.id),
    createdAt: timestamp('created_at').defaultNow(),
    status: intakeStatusEnum('status')
        .default('PENDING')
        .notNull(),
    doctorRemark: text('doctor_remark')
});

export const intakeListings = pgTable("intake_listings", {
    id: uuid("id").defaultRandom().primaryKey(),

    intakeId: uuid("intake_id")
        .notNull()
        .references(() => intakes.id),

    listingId: uuid("listing_id")
        .notNull()
        .references(() => listings.id),
}, (table) => [
    unique().on(table.listingId, table.intakeId)
])

export const usersRelations = relations(
    users,
    ({ one, many }) => ({
        assessment: one(assessments),
        intakes: many(intakes)
    })
);

export const assessmentsRelations = relations(
    assessments,
    ({ one, many }) => ({
        user: one(users, {
            fields: [assessments.userId],
            references: [users.id]
        }),
        assessmentAnswers: many(assessmentAnswers)
    })
);

export const assessmentAnswersRelations = relations(
    assessmentAnswers,
    ({ one }) => ({
        assessment: one(assessments, {
            fields: [assessmentAnswers.assessmentId],
            references: [assessments.id]
        }),
        assessmentQuestion: one(assessmentQuestions, {
            fields: [assessmentAnswers.assessmentQuestionId],
            references: [assessmentQuestions.id]
        })
    })
);

export const assessmentQuestionsRelations = relations(
    assessmentQuestions,
    ({ many }) => ({
        assessmentAnswers: many(assessmentAnswers)
    })
);

export const intakesRelations = relations(
    intakes,
    ({ one, many }) => ({
        user: one(users, {
            fields: [intakes.userId],
            references: [users.id]
        }),
        intakeListings: many(intakeListings)
    })
)

export const listingsRelations = relations(
    listings,
    ({ many }) => ({
        intakeListings: many(intakeListings),
        listingDocuments: many(listingDocuments)
    })
)

export const listingDocumentsRelations = relations(
    listingDocuments,
    ({ one }) => ({
        listing: one(listings, {
            fields: [listingDocuments.listingId],
            references: [listings.id]
        })
    })
)

export const intakeListingsRelations = relations(
    intakeListings,
    ({ one }) => ({
        intake: one(intakes, {
            fields: [intakeListings.intakeId],
            references: [intakes.id]
        }),
        listing: one(listings, {
            fields: [intakeListings.listingId],
            references: [listings.id]
        })
    })
);
